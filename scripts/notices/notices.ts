/**
 * The third-party notices file the app bundle carries (issue #577, D148): how an entry is written,
 * and how a committed file is compared with what the app ships now. Pure: the entries come from
 * `collect.ts`, which reads pnpm's and Cargo's data and the packages' own files.
 *
 * The file lists every shipped package once, grouped by where it comes from, each with the licence
 * it declares, the parts of the app it ships in, and every licence and notice file it carries,
 * word for word. A package that carries none says so; nothing is filled in.
 */
import { createHash } from "node:crypto";

/** Where a package comes from. `other` is software no package manager lists (Bun's runtime, fonts). */
export type Ecosystem = "npm" | "cargo" | "other";

/** One licence or notice file, by the name it has in its package. */
export interface NoticeFile {
	name: string;
	text: string;
}

export interface NoticeEntry {
	ecosystem: Ecosystem;
	name: string;
	version: string;
	/** The licence as the package declares it, or `NOT_DECLARED`. */
	licence: string;
	/** The parts of the app the package ships in, such as "web UI" or "sidecar". */
	shipsIn: readonly string[];
	/** Why a package that is not a runtime dependency is listed, such as a build tool's own code. */
	note?: string;
	files: readonly NoticeFile[];
}

/** The licence line of a package whose manifest names no licence. */
export const NOT_DECLARED = "Not declared by the package";

/** The command that writes the file. Every problem message ends by naming it. */
const GENERATE_COMMAND = "bun scripts/notices/generate.ts";

const ECOSYSTEM_TITLES: Record<Ecosystem, string> = {
	npm: "npm packages",
	cargo: "Rust crates",
	other: "Other software",
};
const ECOSYSTEMS: readonly Ecosystem[] = ["npm", "cargo", "other"];

const RULE = "=".repeat(80);
const THIN_RULE = "-".repeat(80);
const SECTION_RULE = "#".repeat(80);

/** The key a package is known by in the file and in problem messages: `npm zod 4.6.7`. */
export function entryKey(entry: Pick<NoticeEntry, "ecosystem" | "name" | "version">): string {
	return `${entry.ecosystem} ${entry.name} ${entry.version}`;
}

/** Compares by code unit, so the order is the same on every machine and locale. */
function byCodeUnit(a: string, b: string): number {
	return a < b ? -1 : a > b ? 1 : 0;
}

/** Line endings made `\n` and trailing blank lines dropped, so a file reads the same everywhere. */
function normaliseText(text: string): string {
	return text.replace(/\r\n?/g, "\n").replace(/\s+$/, "");
}

/** A shared text's id: the start of its SHA-256, so it stays the same as packages come and go. */
export function textId(text: string): string {
	return createHash("sha256").update(text).digest("hex").slice(0, 12);
}

const SHARED_TITLE = "Shared licence texts";

function renderEntry(entry: NoticeEntry, shared: ReadonlySet<string>): string {
	const lines = [
		RULE,
		`${entry.ecosystem}: ${entry.name} ${entry.version}`,
		`Licence: ${entry.licence}`,
		`Ships in: ${entry.shipsIn.join(", ")}`,
		...(entry.note === undefined ? [] : [`Note: ${entry.note}`]),
	];
	if (entry.files.length === 0) {
		lines.push(THIN_RULE, "The package carries no licence or notice file.");
	}
	for (const file of entry.files) {
		const text = normaliseText(file.text);
		lines.push(THIN_RULE, `File: ${file.name}`, "");
		if (shared.has(text)) lines.push(`The text is ${textId(text)} under "${SHARED_TITLE}" below.`);
		else lines.push(text);
	}
	return `${lines.join("\n")}\n`;
}

/**
 * The whole notices file for these entries. The same entries always give the same text. A text
 * that more than one file carries word for word, such as the Apache licence, is given once at the
 * end under its id, and each file that carries it names the id.
 */
export function renderNotices(entries: readonly NoticeEntry[]): string {
	const sorted = [...entries].sort(
		(a, b) => byCodeUnit(a.name, b.name) || byCodeUnit(a.version, b.version),
	);
	const uses = new Map<string, number>();
	for (const entry of sorted) {
		for (const file of entry.files) {
			const text = normaliseText(file.text);
			uses.set(text, (uses.get(text) ?? 0) + 1);
		}
	}
	const shared = new Set([...uses].filter(([, count]) => count > 1).map(([text]) => text));
	const counts = ECOSYSTEMS.map(
		(ecosystem) =>
			`- ${ECOSYSTEM_TITLES[ecosystem]}: ${sorted.filter((e) => e.ecosystem === ecosystem).length}`,
	);
	const parts = [
		[
			"Third-party notices for Conducted",
			"",
			"Conducted is MIT-licensed. It ships the third-party software below. Each entry names the",
			"software, its version, the licence it declares and the parts of the app it ships in, then",
			"gives every licence and notice file it carries, word for word. A text that several files",
			`carry word for word is given once, under "${SHARED_TITLE}" at the end.`,
			"",
			`Generated by \`${GENERATE_COMMAND}\` from pnpm's and Cargo's dependency data. Change the`,
			"generator, never this file.",
			"",
			...counts,
			"",
		].join("\n"),
	];
	for (const ecosystem of ECOSYSTEMS) {
		parts.push(`${SECTION_RULE}\n${ECOSYSTEM_TITLES[ecosystem]}\n${SECTION_RULE}\n`);
		for (const entry of sorted.filter((e) => e.ecosystem === ecosystem)) {
			parts.push(renderEntry(entry, shared));
		}
	}
	parts.push(`${SECTION_RULE}\n${SHARED_TITLE}\n${SECTION_RULE}\n`);
	const byId = [...shared].map((text) => [textId(text), text] as const);
	for (const [id, text] of byId.sort(([a], [b]) => byCodeUnit(a, b))) {
		parts.push(`${RULE}\nText ${id}\n${THIN_RULE}\n${text}\n`);
	}
	return parts.join("\n");
}

const HEADING = /^(npm|cargo|other): (\S+) (\S+)$/;
const SHARED_REFERENCE = new RegExp(
	`^The text is ([0-9a-f]{12}) under "${SHARED_TITLE}" below\\.$`,
	"gm",
);

/** The shared texts at the end of a notices file, by id. */
function sharedTextsIn(text: string): Map<string, string> {
	const texts = new Map<string, string>();
	const title = `${SECTION_RULE}\n${SHARED_TITLE}\n${SECTION_RULE}\n`;
	const start = text.indexOf(title);
	if (start === -1) return texts;
	for (const chunk of text
		.slice(start + title.length)
		.split(`${RULE}\n`)
		.slice(1)) {
		const heading = /^Text ([0-9a-f]{12})\n/.exec(chunk);
		if (heading?.[1] === undefined) continue;
		const body = chunk.slice(heading[0].length + THIN_RULE.length + 1);
		texts.set(heading[1], body.replace(/\n+$/, ""));
	}
	return texts;
}

/**
 * Each entry's text in a notices file, by its key, with every shared text written back in. Whether
 * a text is shared depends on the other packages, so an entry is compared by what it says.
 */
export function entriesIn(text: string): Map<string, string> {
	const shared = sharedTextsIn(text);
	const blocks = new Map<string, string>();
	for (const chunk of text.split(`${RULE}\n`).slice(1)) {
		const heading = HEADING.exec(chunk.slice(0, chunk.indexOf("\n")));
		if (heading === null) continue;
		const [, ecosystem, name, version] = heading;
		// The last entry of a section runs into the next section's title; that is not the entry's text.
		const end = chunk.indexOf(`\n${SECTION_RULE}\n`);
		const block = end === -1 ? chunk : chunk.slice(0, end + 1);
		blocks.set(
			`${ecosystem} ${name} ${version}`,
			block.replace(SHARED_REFERENCE, (line, id: string) => shared.get(id) ?? line),
		);
	}
	return blocks;
}

/**
 * What is wrong with the committed notices, given what ships now. Empty means current. `committed`
 * is null when the file is missing. Each problem names the package it is about, and the last one
 * says how to fix them all.
 */
export function noticesProblems(
	committed: string | null,
	entries: readonly NoticeEntry[],
	fileName: string,
): string[] {
	const fix = `Run \`${GENERATE_COMMAND}\` and commit ${fileName}.`;
	if (committed === null) return [`${fileName} is missing.`, fix];
	const expected = renderNotices(entries);
	if (committed === expected) return [];

	const want = entriesIn(expected);
	const have = entriesIn(committed);
	const problems: string[] = [];
	for (const [key, block] of want) {
		const listed = have.get(key);
		if (listed === undefined) problems.push(`${key} ships but is not in ${fileName}.`);
		else if (listed !== block) problems.push(`${key} has changed: its licence or files differ.`);
	}
	for (const key of have.keys()) {
		if (!want.has(key)) problems.push(`${key} is in ${fileName} but no longer ships.`);
	}
	if (problems.length === 0) problems.push(`${fileName} is out of date: its introduction differs.`);
	problems.push(fix);
	return problems;
}
