/**
 * The rules the changed-only test run reads (`pnpm test:changed`, scripts/run-tests.ts). They sit
 * in one file, so a change to what runs is one diff.
 *
 * - RUN_EVERYTHING: a change to any of these runs every test. They are what the runners' own
 *   import graphs cannot see: manifests and lockfiles, build, test and CI configuration, the test
 *   run itself, migrations and generated code.
 * - READ_WHOLE: folders some tests read by listing or building them, not by importing them. A
 *   change inside one runs the tests named beside it. A folder of a runner (`apps/cloud`) means
 *   every test of that runner.
 * - ALWAYS: the small set of tests on money, data loss and security paths that runs on every pull
 *   request, whatever changed (the owner's ruling).
 * - MACOS_JOB: what CI's macOS job (`rust`) checks, read or installs. A pull request runs that job
 *   only when it changes one of these (scripts/macos-job.ts); main always runs it.
 *
 * Nothing checks the first three lists against the code but the main line: it runs everything
 * after every merge. When it fails on something a pull request's run skipped, add the path that
 * let it through here. MACOS_JOB is also checked by scripts/macos-job.test.ts, against the paths
 * the Rust crate names and the macOS tests import.
 */

/** A path pattern (Bun.Glob, from the repository root) and why it is on the list. */
export interface Rule {
	glob: string;
	why: string;
}

/** A folder some tests read whole, and those tests. */
export interface FolderRule extends Rule {
	/** Test files, or a runner's folder for every test of that runner. */
	tests: readonly string[];
}

/** A test that runs on every pull request, and the path it guards. */
export interface AlwaysTest {
	file: string;
	why: string;
}

