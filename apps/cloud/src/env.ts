/**
 * @feature CLOUD-03 The user's Worker and one Durable Object per workspace: routes, state, keep-alive, relay
 * Owns: the bindings and secrets the Worker and its Durable Object read.
 * Behaviour: docs/plans/cloud-and-remote.md Part 1 (the Worker authenticates the desktop with a
 * pairing token and routes each workspace to its Durable Object) and its spike result (the token
 * is a Worker secret, the model key stays in the Worker).
 * Must handle: a missing token refuses every request; a missing model key refuses an agent turn
 * instead of starting one with an empty credential.
 * Our design choice: the interface is written by hand rather than generated by `wrangler types`,
 * so `pnpm typecheck` runs without a deploy tool.
 * Test first: a request without the pairing token gets 401 before any Durable Object is touched.
 */
import type { Workspace } from "./workspace.ts";

/** The instance sizes Cloudflare's container platform offers (Containers limits, read 2026-11-06). */
export type InstanceType =
	| "lite"
	| "basic"
	| "standard-1"
	| "standard-2"
	| "standard-3"
	| "standard-4";

export interface Env {
	/** One Durable Object per workspace name. */
	WORKSPACE: DurableObjectNamespace<Workspace>;
	/** Shared secret made when the Worker is deployed; every route checks it. */
	PAIRING_TOKEN: string;
	/** The model key the outbound handler swaps into the sandbox's placeholder. */
	ANTHROPIC_API_KEY: string;
	/** The GitHub token the outbound handler holds for `git` and `gh` (CLOUD-05 extends this). */
	GITHUB_TOKEN?: string;
	/** The container size the sandbox starts in. */
	INSTANCE_TYPE: InstanceType;
}
